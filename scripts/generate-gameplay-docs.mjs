import { createServer } from 'vite';
import { mkdir, writeFile } from 'node:fs/promises';

// Load the actual TypeScript registry, without starting the editor or its plugins.
const server = await createServer({ configFile: false, optimizeDeps: { noDiscovery: true, include: [] }, server: { middlewareMode: true }, appType: 'custom' });
try {
  const { GameplayFeatureRegistry } = await server.ssrLoadModule('/src/features/gameplay/GameplayFeatureRegistry.ts');
  const { GAMEPLAY_PRESETS } = await server.ssrLoadModule('/src/features/gameplay/GameplayPresets.ts');
  const features = GameplayFeatureRegistry.list();
  const rows = features.map(d => `| ${d.id} | ${d.name} | ${(d.requires ?? []).join(', ') || '—'} |`);
  const text = [
    '# Gameplay feature catalog', '',
    'Generated by `npm run docs:gameplay` from the runtime registry. Do not edit manually.', '',
    `${features.length} registered features; ${GAMEPLAY_PRESETS.length} command-addressable presets.`, '',
    '## Presets', '', ...GAMEPLAY_PRESETS.map(p => `- ${p}`), '',
    '## Features', '', '| ID | Name | Required features |', '| --- | --- | --- |', ...rows, '',
  ].join('\n');
  await mkdir('docs', { recursive: true });
  await writeFile('docs/gameplay-features.generated.md', text);
  console.log(`Generated catalog: ${features.length} features, ${GAMEPLAY_PRESETS.length} presets.`);
} finally { await server.close(); }
